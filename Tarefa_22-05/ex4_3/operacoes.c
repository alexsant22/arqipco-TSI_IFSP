// operacoes.c

#include "operacoes.h"

// Adição
float adicao(float a, float b)
{
    return a + b;
}

// Subtração
float subtracao(float a, float b)
{
    return a - b;
}

// Multiplicação
float multiplicacao(float a, float b)
{
    return a * b;
}

// Divisao
float divisao(float a, float b)
{
    return a / b;
}
